-- Adds ASP.NET Core Identity columns and role tables to the existing Users table.
-- Applied after 001_initial_schema.sql during a fresh PostgreSQL initialization.

ALTER TABLE "Users"
  ADD COLUMN IF NOT EXISTS "UserName" varchar(256) NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS "NormalizedUserName" varchar(256),
  ADD COLUMN IF NOT EXISTS "NormalizedEmail" varchar(256),
  ADD COLUMN IF NOT EXISTS "EmailConfirmed" boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS "PasswordHash" text,
  ADD COLUMN IF NOT EXISTS "SecurityStamp" text,
  ADD COLUMN IF NOT EXISTS "ConcurrencyStamp" text,
  ADD COLUMN IF NOT EXISTS "PhoneNumber" text,
  ADD COLUMN IF NOT EXISTS "PhoneNumberConfirmed" boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS "TwoFactorEnabled" boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS "LockoutEnd" timestamptz,
  ADD COLUMN IF NOT EXISTS "LockoutEnabled" boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS "AccessFailedCount" integer NOT NULL DEFAULT 0;

UPDATE "Users"
SET "UserName" = "Email"
WHERE "UserName" = '';

UPDATE "Users"
SET "NormalizedUserName" = upper("UserName"),
    "NormalizedEmail" = upper("Email")
WHERE "NormalizedUserName" IS NULL OR "NormalizedEmail" IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS "UserNameIndex" ON "Users" ("NormalizedUserName");
CREATE UNIQUE INDEX IF NOT EXISTS "EmailIndex" ON "Users" ("NormalizedEmail");

CREATE TABLE IF NOT EXISTS "AspNetRoles" (
  "Id" uuid PRIMARY KEY,
  "Name" varchar(256),
  "NormalizedName" varchar(256),
  "ConcurrencyStamp" text
);
CREATE UNIQUE INDEX IF NOT EXISTS "RoleNameIndex" ON "AspNetRoles" ("NormalizedName");

CREATE TABLE IF NOT EXISTS "AspNetRoleClaims" (
  "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "RoleId" uuid NOT NULL REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE,
  "ClaimType" text,
  "ClaimValue" text
);
CREATE INDEX IF NOT EXISTS "IX_AspNetRoleClaims_RoleId" ON "AspNetRoleClaims" ("RoleId");

CREATE TABLE IF NOT EXISTS "AspNetUserClaims" (
  "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "UserId" uuid NOT NULL REFERENCES "Users" ("Id") ON DELETE CASCADE,
  "ClaimType" text,
  "ClaimValue" text
);
CREATE INDEX IF NOT EXISTS "IX_AspNetUserClaims_UserId" ON "AspNetUserClaims" ("UserId");

CREATE TABLE IF NOT EXISTS "AspNetUserLogins" (
  "LoginProvider" varchar(128) NOT NULL,
  "ProviderKey" varchar(128) NOT NULL,
  "ProviderDisplayName" text,
  "UserId" uuid NOT NULL REFERENCES "Users" ("Id") ON DELETE CASCADE,
  PRIMARY KEY ("LoginProvider", "ProviderKey")
);
CREATE INDEX IF NOT EXISTS "IX_AspNetUserLogins_UserId" ON "AspNetUserLogins" ("UserId");

CREATE TABLE IF NOT EXISTS "AspNetUserRoles" (
  "UserId" uuid NOT NULL REFERENCES "Users" ("Id") ON DELETE CASCADE,
  "RoleId" uuid NOT NULL REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE,
  PRIMARY KEY ("UserId", "RoleId")
);
CREATE INDEX IF NOT EXISTS "IX_AspNetUserRoles_RoleId" ON "AspNetUserRoles" ("RoleId");

CREATE TABLE IF NOT EXISTS "AspNetUserTokens" (
  "UserId" uuid NOT NULL REFERENCES "Users" ("Id") ON DELETE CASCADE,
  "LoginProvider" varchar(128) NOT NULL,
  "Name" varchar(128) NOT NULL,
  "Value" text,
  PRIMARY KEY ("UserId", "LoginProvider", "Name")
);
